"""Print-manuscript letter skeletons in stroke order.
Units: baseline y=0, cap height y=1, x-height y=0.5, descender y=-0.5. Each letter = (width, [stroke, ...]);
each stroke is a list of (x, y) points in writing direction. A one-point stroke is a dot (i, j)."""
import math

def L(*pts): return list(pts)

def arc(cx, cy, rx, ry, a0, a1, n=None):
    """angles in degrees, math convention (y up); goes from a0 to a1 (sign gives direction)."""
    n = n or max(8, int(abs(a1 - a0) / 6))
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)), cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]

def cat(*parts):
    out = []
    for p in parts:
        if out and math.dist(out[-1], p[0]) < 1e-6: p = p[1:]
        out += p
    return out

